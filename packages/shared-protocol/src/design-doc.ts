import { SceneGraphDocument } from "@frameforge/scene-graph";
import { analyzeSceneGraph } from "./inspector.js";

export function generateDesignDoc(doc: SceneGraphDocument): string {
  const analysis = analyzeSceneGraph(doc);

  const colorRows = analysis.colors
    .slice(0, 15)
    .map(
      (c) =>
        `| \`${c.hex}\` | \`${c.rgb}\` | \`${c.hsl}\` | \`${c.nearestTailwind.name}\` | ${c.count} |`
    )
    .join("\n");

  const typoRows = analysis.typography
    .slice(0, 10)
    .map(
      (t) =>
        `| **${t.fontFamily}** | ${t.weight} | ${t.fontSize}px | ${t.lineHeight || "auto"} | "${t.sampleText}" | ${t.count} |`
    )
    .join("\n");

  const assetRows = analysis.assets
    .slice(0, 10)
    .map(
      (a) =>
        `| ${a.type} | ${a.name} | ${a.dimensions.width}×${a.dimensions.height} | ${a.srcUrl ? `[Link](${a.srcUrl})` : "Inline"} |`
    )
    .join("\n");

  const a11ySummary =
    analysis.accessibility.issues.length === 0
      ? "✅ All evaluated text elements passed WCAG 2.1 AA contrast thresholds."
      : `⚠️ Found **${analysis.accessibility.issues.length}** elements with potential contrast issues under WCAG AA:\n\n` +
        analysis.accessibility.issues
          .slice(0, 5)
          .map(
            (issue) =>
              `- Text: "${issue.textSnippet}" (${issue.fontSize}px) — Ratio: ${issue.contrastResult.contrastRatioFormatted} (AA requires ${issue.contrastResult.isLargeText ? "3:0:1" : "4.5:1"})`
          )
          .join("\n");

  return `# DESIGN.md — Extracted Design System Specification

Generated by **FrameForge** on ${doc.capturedAt}.
- **Source URL**: ${doc.url}
- **Document Title**: ${doc.title}
- **Viewport**: ${doc.viewport.width}×${doc.viewport.height} (DPR: ${doc.viewport.devicePixelRatio})
- **Capture Mode**: ${doc.captureMode}

---

## 1. Color Palette Tokens

| Hex | RGB | HSL | Nearest Tailwind Token | Occurrences |
| :--- | :--- | :--- | :--- | :--- |
${colorRows}

---

## 2. Typography Scale

| Font Family | Weight | Font Size | Line Height | Sample Text | Occurrences |
| :--- | :--- | :--- | :--- | :--- | :--- |
${typoRows}

---

## 3. Asset Inventory

| Type | Name | Dimensions | Source |
| :--- | :--- | :--- | :--- |
${assetRows || "| None | - | - | - |"}

---

## 4. Accessibility Observations (WCAG 2.1)

${a11ySummary}

---

## 5. Layout & Component Structure

- **Root Dimensions**: ${doc.root.bounds.width}×${doc.root.bounds.height}px
- **Total Nodes Captured**: ${doc.diagnostics.totalNodesCaptured}
- **Editable Text Layers**: ${doc.diagnostics.totalTextNodes}
- **Images Reconstructed**: ${doc.diagnostics.totalImages}
- **Vectors / SVGs**: ${doc.diagnostics.totalVectors}
- **Layout Inference**: Confident CSS Flexbox layouts mapped to Figma Auto Layout; complex grids use fixed constraints.
`;
}
